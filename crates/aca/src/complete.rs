//! zsh completion: `aca completion zsh` prints a script; once installed, every Tab press asks
//! `aca __complete <WORDS TYPED…> <WORD BEING TYPED>`.
//!
//! What to complete follows the usages in help.rs: `<id>` completes sessions, `-g GROUP` groups (plus a `.` = decided by
//! directory), `[DIR]` is handed to zsh to complete directories,
//! fixed words (`group rename`, `cost [1|7|30|all]`) are completed as is. So adding a command only takes writing its usage in
//! help.rs, nothing here;
//! for a new placeholder word in a usage, say in `kind` what it completes, or record it in `FREE` (a test checks that every
//! placeholder word is known).
//! The script itself is thin and carries no command table: added commands and changed sessions and groups never need it
//! regenerated.
//!
//! Output is one candidate per line: `KIND\tVALUE\tNOTE`, the same kind together; a `dirs` line = let zsh complete directories
//! itself.
//! In a zsh with fzf-tab it's an fzf pick (the notes are searchable too: type a title or a group name).
//!
//! Usages are split in the current language: Chinese placeholders are hanzi and fixed words ASCII; English placeholders are all
//! uppercase and fixed words lowercase.
//! `kind` knows both, and a test checks that the same usage line splits the same way in both languages.

