/// The zsh completion function. Put it in fpath as `_aca` (loaded on the first Tab), or `eval "$(aca completion zsh)"`.
/// The title of each kind of candidate follows the language at generation time: fzf-tab previews rely on it to tell whether
/// it's sessions (`$group == *会话*`)
pub fn zsh() -> String {
    let head = match lang() {
        Lang::Zh => "command 命令 sub 子命令 flag 选项 session 会话 group 分组 tool 工具 tmux 'tmux 会话' topic 说明",
        Lang::En => "command command sub subcommand flag option session session group group tool tool tmux 'tmux session' topic topic",
    };
    ZSH.replace("{HEAD}", head)
}

const ZSH: &str = r#"#compdef aca
# zsh completion for aca (generated by aca completion zsh). Candidates are asked of aca itself every time (aca __complete),
# so added commands and changed sessions and groups never need it regenerated. With fzf-tab installed, it's an fzf pick.

_aca() {
  local -A head=({HEAD})
  local -a vals parts
  local line t tag= ret=1
  # An empty line added at the end: hands over the last kind too
  for line in "${(@f)$(${words[1]} __complete -- "${(@)words[2,CURRENT]}" 2>/dev/null)}" ''; do
    parts=("${(@ps:\t:)line}")
    t=${parts[1]}
    if [[ -n $tag && $t != $tag ]]; then
      if [[ $tag == dirs ]]; then
        _path_files -/ && ret=0
      else
        # -V: in the order aca gives (sessions most recently active first), not re-sorted alphabetically
        _describe -V -t $tag "${head[$tag]:-$tag}" vals && ret=0
      fi
      vals=()
    fi
    tag=$t
    [[ -z $t || $t == dirs ]] && continue
    vals+=("${parts[2]//:/\\:}${parts[3]:+:${parts[3]}}")
  done
  return ret
}

# fzf-tab re-sorts alphabetically by default: turn it off so sessions are most recently active first (left alone if you set it yourself)
[[ -n $(zstyle -L ':completion:*:aca:*' sort) ]] || zstyle ':completion:*:aca:*' sort false

if [[ $funcstack[1] == _aca ]]; then
  _aca "$@"
else
  compdef _aca aca
fi
"#;

/// What an argument completes
#[derive(Clone, Copy, Debug, PartialEq)]
enum Kind {
    /// Registered sessions (`unarchive` completes archived ones)
    Session,
    /// Existing groups; dot = also offer a `.` (group decided by directory)
    Group {
        dot: bool,
    },
    Dir,
    /// From `aca names`: tools, accounts
    Tool,
    /// tmux sessions not registered yet (for `adopt`)
    Tmux,
    /// Free text (a title, a message, a number): nothing completed
    Free,
}

/// What a placeholder word in a usage completes (Chinese ones, English ones)
fn kind(p: &str) -> Kind {
    match p {
        "id" | "会话 id" => Kind::Session,
        "分组" | "GROUP" => Kind::Group { dot: true },
        // In the group subcommands, the PATH placeholder is the group's own path (work/app)
        "路径" | "PATH" => Kind::Group { dot: false },
        "目录" | "默认目录" | "本地目录" | "DIR" | "DEFAULT-DIR" | "LOCAL-DIR" => Kind::Dir,
        "工具[:账号]" | "工具名" | "TOOL[:ACCOUNT]" | "TOOL-NAME" => Kind::Tool,
        "tmux 会话" | "%窗格" | "TMUX-SESSION" | "%PANE" => Kind::Tmux,
        _ => Kind::Free,
    }
}

/// A word typed as is: lowercase letters, digits, - _ (`popup`, `30`, `agent-deck`); English placeholders are all uppercase
/// and don't count
fn literal(w: &str) -> bool {
    w.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' || c == '_')
}

